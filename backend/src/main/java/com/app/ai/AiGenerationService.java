  private String documentPrompt(String prompt) {
    return """
        You write technical design documents for system design interview preparation.
        Return Markdown only. Do not wrap the answer in code fences.

        Include these sections exactly:
        # <System Name>
        ## Overview
        ## Requirements
        ### Functional Requirements
        ### Non Functional Requirements
        ## Capacity Estimation
        ## Core Components
        ## APIs
        ## Database Design
        ## Scaling
        ## Bottlenecks
        ## Security
        ## Tradeoffs
        ## Interview Discussion Points

        Keep the answer practical, concise, and backend-system focused.

        User prompt: %s
        """
        .formatted(prompt);
  }

  private String titleFromPrompt(String prompt) {
    String lowerPrompt = prompt.toLowerCase(Locale.ROOT);
    if (lowerPrompt.contains("url")
        && (lowerPrompt.contains("shortener") || lowerPrompt.contains("shortner"))) {
      return "URL Shortener";
    }
    String normalized =
        prompt
            .replaceFirst(
                "(?i)^\\s*(design|create|build|make|generate|document|documentation\\s+for)\\s+",
                "")
            // "design me splitwise" and "build a chat app" otherwise keep the filler
            // word and title themselves "Me Splitwise" / "A Chat App".
            .replaceFirst("(?i)^\\s*(me|us|for\\s+me|a|an|the|my|our)\\s+", "")
            .trim();
    if (normalized.isBlank()) {
      return "Generated System Design";
    }
    String[] words = normalized.split("\\s+");
    List<String> titleWords = new ArrayList<>();
    for (int index = 0; index < Math.min(words.length, 6); index++) {
      String word = words[index].replaceAll("[^A-Za-z0-9-]", "");
      if (!word.isBlank()) {
        titleWords.add(word.substring(0, 1).toUpperCase(Locale.ROOT) + word.substring(1));
      }
    }
    return titleWords.isEmpty() ? "Generated System Design" : String.join(" ", titleWords);
  }

  private List<String> interviewQuestionsFor(String prompt) {
    MockSystemDesign fallback = designFor(prompt);
    return fallback.interviewQuestions();
  }

  private MockSystemDesign designFor(String prompt) {
    String normalized = prompt.toLowerCase(Locale.ROOT);
    if (normalized.contains("url") || normalized.contains("shortener") || normalized.contains("shortner")) {
      return urlShortenerDesign();
    }
    if (normalized.contains("whatsapp") || normalized.contains("chat")) {
      return whatsappDesign();
    }
    if (normalized.contains("netflix") || normalized.contains("stream")) {
      return netflixDesign();
    }
    if (normalized.contains("youtube") || normalized.contains("recommend")) {
      return youtubeDesign();
    }
    if (normalized.contains("uber")
        || (normalized.contains("driver") && normalized.contains("tracking"))) {
      return uberDesign();
    }
    return genericDesign(prompt);
  }

  private String modelOrDefault(String model) {
    return model == null || model.isBlank() ? ollamaProperties.defaultModel() : model;
  }

  private String fallbackMessage(RuntimeException exception, String artifactType) {
    String detail =
        exception.getMessage() == null || exception.getMessage().isBlank()
            ? "Ollama was unavailable"
            : exception.getMessage();
    detail = detail.replaceFirst("[.!?]+$", "");
    return "%s. Showing deterministic mock %s instead.".formatted(detail, artifactType);
  }

  private JsonNode graphFor(MockSystemDesign design) {
    return objectMapper.valueToTree(Map.of("nodes", design.nodes(), "edges", design.edges()));
  }

  private String markdownFor(MockSystemDesign design) {
    return """
        # %s

        ## Overview

        %s

        ## Requirements

        ### Functional Requirements

        %s

        ### Non Functional Requirements

        - Low latency user-facing paths.
        - Horizontally scalable stateless services.
        - Durable event history for replay and recovery.
        - Regional isolation for high traffic spikes.

        ## Capacity Estimation

        | Metric | Mock Estimate |
        | --- | ---: |
        | Peak requests | 250k/sec |
        | Hot data TTL | 5-30 min |
        | Availability target | 99.95%% |

        ## Core Components

        %s

        ## APIs

        ```http
        POST /v1/events
        GET /v1/resources/{id}
        WS /v1/realtime/{channel}
        ```

        ## Database Design

        Use the operational database for durable state, cache hot read paths, and stream events into analytics/storage consumers.

        ## Scaling

        %s

        ## Bottlenecks

        %s

        ## Security

        Authenticate every client, rate limit public entry points, encrypt sensitive data, and scope service-to-service access by least privilege.

        ## Tradeoffs

        %s

        ## Interview Discussion Points

        %s
        """
        .formatted(
            design.title(),
            design.overview(),
            bulletList(design.functionalRequirements()),
            bulletList(design.components()),
            design.scaling(),
            bulletList(design.bottlenecks()),
            design.tradeoffs(),
            bulletList(design.interviewQuestions()));
  }

  private String bulletList(List<String> values) {
    return values.stream().map(value -> "- " + value).reduce("", (left, right) -> left + right + "\n");
  }

