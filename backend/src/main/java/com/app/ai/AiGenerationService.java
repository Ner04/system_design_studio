  public AiGenerationService(
      ObjectMapper objectMapper,
      OllamaClient ollamaClient,
      OllamaJsonSanitizer jsonSanitizer,
      OllamaProperties ollamaProperties) {
    this.objectMapper = objectMapper;
    this.ollamaClient = ollamaClient;
    this.jsonSanitizer = jsonSanitizer;
    this.ollamaProperties = ollamaProperties;
  }

  public AiGenerationResponse generateDiagram(AiGenerateDiagramRequest request) {
    String model = modelOrDefault(request.model());
    if (ollamaProperties.enabled()) {
      try {
        JsonNode graph = generateOllamaGraph(request.prompt(), model);
        String title = titleFromPrompt(request.prompt());
        return new AiGenerationResponse(
            "OLLAMA",
            "Generated architecture graph JSON with local Ollama model.",
            model,
            title,
            graph,
            null,
            List.of("Graph generated by local Ollama. Layout remains handled by the frontend."),
            interviewQuestionsFor(request.prompt()));
      } catch (RuntimeException exception) {
        MockSystemDesign fallback = designFor(request.prompt());
        return new AiGenerationResponse(
            "MOCK_FALLBACK",
            fallbackMessage(exception, "graph JSON"),
            model,
            fallback.title(),
            graphFor(fallback),
            null,
            fallback.explanation(),
            fallback.interviewQuestions());
      }
    }

    MockSystemDesign design = designFor(request.prompt());
    return new AiGenerationResponse(
        "MOCK_AI",
        "Generated deterministic mock architecture graph JSON. Enable Ollama to use a local model.",
        model,
        design.title(),
        graphFor(design),
        null,
        design.explanation(),
        design.interviewQuestions());
  }

  public AiGenerationResponse generateDocument(AiGenerateDocumentRequest request) {
    String model = modelOrDefault(request.model());
    if (ollamaProperties.enabled()) {
      try {
        String markdown = generateOllamaDocument(request.prompt(), model);
        return new AiGenerationResponse(
            "OLLAMA",
            "Generated technical design document with local Ollama model.",
            model,
            titleFromPrompt(request.prompt()),
            null,
            markdown,
            List.of("Document generated by local Ollama."),
            interviewQuestionsFor(request.prompt()));
      } catch (RuntimeException exception) {
        MockSystemDesign fallback = designFor(request.prompt());
        return new AiGenerationResponse(
            "MOCK_FALLBACK",
            fallbackMessage(exception, "Markdown"),
            model,
            fallback.title(),
            null,
            markdownFor(fallback),
            fallback.explanation(),
            fallback.interviewQuestions());
      }
    }

    MockSystemDesign design = designFor(request.prompt());
    return new AiGenerationResponse(
        "MOCK_AI",
        "Generated deterministic mock technical design document. Enable Ollama to use a local model.",
        model,
        design.title(),
        null,
        markdownFor(design),
        design.explanation(),
        design.interviewQuestions());
  }

  private JsonNode generateOllamaGraph(String prompt, String model) {
    RuntimeException lastFailure = null;
    for (int attempt = 0; attempt < ollamaProperties.retries(); attempt++) {
      try {
        String rawResponse = ollamaClient.generate(model, diagramPrompt(prompt), true);
        JsonNode graph =
            jsonSanitizer
                .sanitizeGraph(rawResponse)
                .orElseThrow(() -> new IllegalStateException("Ollama returned malformed graph JSON"));
        List<String> problems = jsonSanitizer.structuralProblems(graph);
        if (!problems.isEmpty()) {
          throw new IllegalStateException(
              "Ollama returned an unusable graph (%s)".formatted(String.join("; ", problems)));
        }
        return graph;
      } catch (RuntimeException exception) {
        lastFailure = exception;
        if (exception instanceof OllamaUnavailableException) {
          break;
        }
      }
    }
    throw lastFailure == null ? new IllegalStateException("Ollama graph generation failed") : lastFailure;
  }

  private String generateOllamaDocument(String prompt, String model) {
    RuntimeException lastFailure = null;
    for (int attempt = 0; attempt < ollamaProperties.retries(); attempt++) {
      try {
        String markdown = ollamaClient.generate(model, documentPrompt(prompt), false).trim();
        if (markdown.startsWith("```")) {
          markdown = markdown.replaceFirst("(?s)^```(?:markdown)?\\s*", "").replaceFirst("(?s)\\s*```$", "");
        }
        if (!markdown.contains("## Overview")) {
          throw new IllegalStateException("Ollama document missed required sections");
        }
        return markdown;
      } catch (RuntimeException exception) {
        lastFailure = exception;
        if (exception instanceof OllamaUnavailableException) {
          break;
        }
      }
    }
    throw lastFailure == null ? new IllegalStateException("Ollama document generation failed") : lastFailure;
  }

